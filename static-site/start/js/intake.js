function buildSummary(){
  const out=[];
  steps.forEach(sec=>{
    const n=Number(sec.dataset.step); if(n<1||n>LAST) return;
    const rows=[];
    const read=(field,prefix)=>{
      if(field.closest('[data-show-if][hidden]')) return;
      const lab=field.querySelector(':scope > label:not(.nohave), :scope > .q');
      const vals=[];
      field.querySelectorAll('input,select,textarea').forEach(el=>{
        if(el.closest('.nohave')||el.type==='file'||el.id==='depAck') return;
        if(el.type==='checkbox'||el.type==='radio'){ if(el.checked) vals.push(txt(el.nextElementSibling)); }
        else if(el.tagName==='SELECT'){ if(el.value) vals.push(txt(el.selectedOptions[0])); }
        else if(el.value.trim()) vals.push(el.value.trim());
      });
      const need=field.querySelector('[data-need]:checked');
      if(need) vals.push(lang==='es'?'(todavía no lo tiene)':'(does not have it yet)');
      if(vals.length) rows.push([(prefix||'')+(txt(lab)||'-'),vals.join(field.querySelector('.dims')?' x ':', ')]);
    };
    if(n===4){
      [...prodList.children].forEach((p,i)=>p.querySelectorAll('.field').forEach(f=>read(f,(lang==='es'?'Producto ':'Product ')+(i+1)+': ')));
      sec.querySelectorAll(':scope > .opt').forEach(o=>{ const i=o.querySelector('input'); if(i.checked) rows.push([txt(o),lang==='es'?'Sí':'Yes']); });
    } else {
      sec.querySelectorAll('.field').forEach(f=>{ if(!f.querySelector('#needed')) read(f); });
      sec.querySelectorAll(':scope > .opt').forEach(o=>{ const i=o.querySelector('input'); if(i.checked) rows.push([txt(o),lang==='es'?'Sí':'Yes']); });
    }
    if(rows.length) out.push({title:txt(sec.querySelector('h1')),rows});
  });
  return out;
}
