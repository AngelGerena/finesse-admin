/* Conditional fields */
function syncShow(){
  form.querySelectorAll('[data-show-if]').forEach(el=>{
    const [n,vals]=el.dataset.showIf.split(':');
    const show=vals.split('|').some(v=>{const i=form.querySelector(`[name="${n}"][value="${v}"]`);return i&&i.checked});
    el.hidden=!show;
  });
}

/* "Don't have it yet" toggles */
function syncNeed(cb){
  const f=cb.closest('.field');
  f.querySelectorAll('input,select,textarea').forEach(el=>{ if(el!==cb && !el.closest('.nohave')) el.disabled=cb.checked; });
}
function buildNeeded(){
  const ul=document.getElementById('needed'); ul.innerHTML='';
  const seen=new Set();
  form.querySelectorAll('[data-need]:checked').forEach(cb=>{
    const k=cb.dataset.need; if(seen.has(k)) return; seen.add(k);
    const li=document.createElement('li');
    li.innerHTML='<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="9"/><path d="M12 7v5l3 2"/></svg>';
    li.append(t(k)); ul.appendChild(li);
  });
  if(!seen.size){ const p=document.createElement('li'); p.style.border='0'; p.innerHTML='<span class="allset"></span>'; p.firstChild.textContent=t('allSet'); ul.appendChild(p); }
}

