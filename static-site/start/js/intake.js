/* Save / restore */
function collect(){
  const data={}, multi={};
  form.querySelectorAll('input,select,textarea').forEach((el,idx)=>{
    if(el.type==='file') return;
    const key=(el.id||el.name||'x')+'#'+idx;
    if(el.type==='checkbox'||el.type==='radio') multi[key]=el.checked; else data[key]=el.value;
  });
  return {data,multi,lang,step:Math.min(step,LAST),visited:[...visited],prods:prodList.children.length};
}
function save(quiet){ store(false,collect()); if(!quiet) toast(t('saved')); }
document.getElementById('saveBtn').addEventListener('click',()=>save(false));
function restore(){
  const s=store(true); if(!s){ addProduct(); return; }
  for(let i=0;i<(s.prods||1);i++) addProduct();
  form.querySelectorAll('input,select,textarea').forEach((el,idx)=>{
    if(el.type==='file') return;
    const key=(el.id||el.name||'x')+'#'+idx;
    if(key in (s.multi||{})) el.checked=s.multi[key]; else if(key in (s.data||{})) el.value=s.data[key];
  });
  lang=s.lang||'en'; step=s.step||0; visited=new Set(s.visited||[0]);
  
}
